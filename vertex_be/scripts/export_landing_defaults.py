"""Writes the landing blocks' built-in text (app/services/landing_content.py)
where the two apps keep it, to show when FastAPI can't answer, so the
pages never go blank:

- the website's: vertex/src/server/services/landing.defaults.json;
- the mobile app's: vertex_app/lib/core/landing/landing_defaults.g.dart
  (the same JSON in a Dart string, read without an asset load).

Run after changing a default or a block, from vertex_be/:

    python scripts/export_landing_defaults.py

tests/test_landing_content.py fails while either file is stale.
"""

import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
os.environ.setdefault("DATABASE_URL", "postgresql://unused@localhost/unused")

from app.services.landing_content import BLOCK_VERSION, blocks_for  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "vertex" / "src" / "server" / "services" / "landing.defaults.json"
MOBILE_OUT = ROOT / "vertex_app" / "lib" / "core" / "landing" / "landing_defaults.g.dart"


def _json(app: str) -> str:
    blocks = {spec.key: spec.default for spec in blocks_for(app)}
    return json.dumps({"version": BLOCK_VERSION, "blocks": blocks}, indent=1, ensure_ascii=False)


def defaults_text() -> str:
    return _json("web") + "\n"


def mobile_defaults_text() -> str:
    body = _json("mobile")
    # A raw string holds any text but its own closing quotes.
    assert "'''" not in body, "a default contains '''"
    return (
        "// GENERATED by vertex_be/scripts/export_landing_defaults.py; do not edit.\n"
        "// The home screen's built-in text (vertex_be/app/services/landing_content.py),\n"
        "// shown until the landing CMS answers (lib/core/landing/landing_store.dart).\n\n"
        f"const landingDefaultsJson = r'''{body}''';\n"
    )


def _read(path: Path) -> str:
    # As committed: Git may check a file out with CRLF on Windows.
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


if __name__ == "__main__":
    OUT.write_text(defaults_text(), encoding="utf-8", newline="\n")
    MOBILE_OUT.parent.mkdir(parents=True, exist_ok=True)
    MOBILE_OUT.write_text(mobile_defaults_text(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}\nwrote {MOBILE_OUT}")
