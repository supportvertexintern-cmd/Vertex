#!/usr/bin/env sh
# Writes .env for the local test stack (docker-compose.yml at the repo root)
# with fresh random passwords and secrets, then prints the URLs. Env files
# are never committed, not even templates (.gitignore), so this script is
# the template.
#
#   sh scripts/local-env.sh            # refuses to overwrite an existing .env
#   sh scripts/local-env.sh --force    # new secrets; existing data volumes
#                                      # keep the old ones, so run
#                                      # `docker compose down -v` first
set -eu

cd "$(dirname "$0")/.."
if [ -f .env ] && [ "${1:-}" != "--force" ]; then
  echo ".env already exists; keeping it (use --force to replace it)." >&2
  exit 1
fi

secret() { openssl rand -hex "${1:-24}"; }

BACKEND_PORT=8010
NEXTJS_PORT=3010
FLUTTER_PORT=8090
PGADMIN_PORT=5070
MAIL_UI_PORT=8035
MINIO_CONSOLE_PORT=9011
POSTGRES_HOST_PORT=15433
MINIO_ROOT_USER=vertex-root
MINIO_ROOT_PASSWORD="$(secret)"
PGADMIN_PASSWORD="$(secret 12)"

umask 077
cat > .env <<EOF
# Local test stack (docker-compose.yml). Generated by scripts/local-env.sh
# on $(date -u +%Y-%m-%dT%H:%MZ). Never commit this file.

# Builds tag their images with this (never pushed).
IMAGE_TAG=local
# pgAdmin is a profile in the deployed stacks; on here.
COMPOSE_PROFILES=pgadmin

APP_ENV=development
DEBUG=false

BACKEND_PORT=$BACKEND_PORT
NEXTJS_PORT=$NEXTJS_PORT
FLUTTER_PORT=$FLUTTER_PORT
PGADMIN_PORT=$PGADMIN_PORT
MAIL_UI_PORT=$MAIL_UI_PORT
MINIO_CONSOLE_PORT=$MINIO_CONSOLE_PORT
# Postgres on 127.0.0.1, for scripts/local-seed.sh and database tools.
POSTGRES_HOST_PORT=$POSTGRES_HOST_PORT

# Postgres superuser (administration only) and the role each service uses.
POSTGRES_DB=vertexdb
POSTGRES_USER=vertex_admin
POSTGRES_PASSWORD=$(secret)
DB_MIGRATOR_PASSWORD=$(secret)
DB_API_PASSWORD=$(secret)
DB_WEB_PASSWORD=$(secret)
DB_READONLY_PASSWORD=$(secret)

SECRET_KEY=$(secret 32)
JWT_SECRET=$(secret 32)
CORS_ORIGINS=["http://localhost:$NEXTJS_PORT", "http://localhost:$FLUTTER_PORT"]
PUBLIC_API_URL=http://localhost:$BACKEND_PORT/api/v1
NEXT_PUBLIC_APP_URL=http://localhost:$NEXTJS_PORT

PGADMIN_EMAIL=admin@example.com
PGADMIN_PASSWORD=$PGADMIN_PASSWORD

# MinIO: root login (console only) and the app's own key for its bucket.
# MINIO_DATA_DIR is the stack's named volume; a host path works too.
MINIO_DATA_DIR=minio_data
MINIO_ROOT_USER=$MINIO_ROOT_USER
MINIO_ROOT_PASSWORD=$MINIO_ROOT_PASSWORD
S3_BUCKET=vertex-local
S3_ACCESS_KEY_ID=vertex-app-local
S3_SECRET_ACCESS_KEY=$(secret)

# Optional integrations stay off unless set (Stripe, PayPal, Google, SMTP;
# mail goes to Mailpit). See vertex_be/docker-compose.deploy.yml.
EOF

cat <<EOF
Wrote .env with fresh secrets. Start the stack:

  docker compose up -d --build

  Web (Next.js)    http://localhost:$NEXTJS_PORT
  App (Flutter)    http://localhost:$FLUTTER_PORT
  API docs         http://localhost:$BACKEND_PORT/docs
  pgAdmin          http://localhost:$PGADMIN_PORT  (admin@example.com / PGADMIN_PASSWORD in .env;
                   database password: DB_READONLY_PASSWORD)
  MinIO console    http://localhost:$MINIO_CONSOLE_PORT  ($MINIO_ROOT_USER / MINIO_ROOT_PASSWORD in .env)
  Mail (Mailpit)   http://localhost:$MAIL_UI_PORT
  Postgres         localhost:$POSTGRES_HOST_PORT  (database vertexdb)

Then load the reference data and test accounts:

  sh scripts/local-seed.sh
EOF
